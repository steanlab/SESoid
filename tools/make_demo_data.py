#!/usr/bin/env python3
"""Generates ble_demo_data.h for the demo pictures that cannot be computed per pixel:
the generalized Hilbert curve over the whole panel (cell table) and the Barnsley fern (1-bit bitmap).
Usage: python tools/make_demo_data.py > ble_demo_data.h
"""
import numpy as np

W, H = 720, 256

def gilbert(x, y, ax, ay, bx, by, out):
    w = abs(ax + ay); h = abs(bx + by)
    dax, day = (ax > 0) - (ax < 0), (ay > 0) - (ay < 0)
    dbx, dby = (bx > 0) - (bx < 0), (by > 0) - (by < 0)
    if h == 1:
        for _ in range(w): out.append((x, y)); x += dax; y += day
        return
    if w == 1:
        for _ in range(h): out.append((x, y)); x += dbx; y += dby
        return
    ax2, ay2 = ax // 2, ay // 2; bx2, by2 = bx // 2, by // 2
    w2 = abs(ax2 + ay2); h2 = abs(bx2 + by2)
    if 2 * w > 3 * h:
        if w2 % 2 and w > 2: ax2 += dax; ay2 += day
        gilbert(x, y, ax2, ay2, bx, by, out); gilbert(x + ax2, y + ay2, ax - ax2, ay - ay2, bx, by, out)
    else:
        if h2 % 2 and h > 2: bx2 += dbx; by2 += dby
        gilbert(x, y, bx2, by2, ax2, ay2, out)
        gilbert(x + bx2, y + by2, ax, ay, bx - bx2, by - by2, out)
        gilbert(x + (ax - dax) + (bx2 - dbx), y + (ay - day) + (by2 - dby), -bx2, -by2, -(ax - ax2), -(ay - ay2), out)

CELL = 8
GW, GH = (W - 8) // CELL, (H - 8) // CELL
pts = []; gilbert(0, 0, GW, 0, 0, GH, pts)
assert len(pts) == GW * GH and len(set(pts)) == len(pts)
seg = len(pts) // 6
tab = [0] * (GW * GH)
for i, (x, y) in enumerate(pts):
    e = 0
    for j in (i - 1, i + 1):
        if 0 <= j < len(pts):
            dx, dy = pts[j][0] - x, pts[j][1] - y
            assert abs(dx) + abs(dy) == 1
            e |= {(1, 0): 1, (0, 1): 2, (-1, 0): 4, (0, -1): 8}[(dx, dy)]
    tab[y * GW + x] = e | (min(i // seg, 5) << 4)

# Barnsley fern, rotated: stem on the left, tip on the right
rng = np.random.default_rng(1); N = 400000
r = rng.random(N); x = y = 0.0; xs = np.empty(N); ys = np.empty(N)
for i in range(N):
    p = r[i]
    if p < 0.01: x, y = 0, 0.16 * y
    elif p < 0.86: x, y = 0.85 * x + 0.04 * y, -0.04 * x + 0.85 * y + 1.6
    elif p < 0.93: x, y = 0.2 * x - 0.26 * y, 0.23 * x + 0.22 * y + 1.6
    else: x, y = -0.15 * x + 0.28 * y, 0.26 * x + 0.24 * y + 0.44
    xs[i] = x; ys[i] = y
u, v = ys, xs
sc = min((W - 30) / (u.max() - u.min()), (H - 16) / (v.max() - v.min()))
px = ((u - u.min()) * sc + (W - (u.max() - u.min()) * sc) / 2).astype(int)
py = (H / 2 - (v - (v.max() + v.min()) / 2) * sc).astype(int)
ok = (px >= 0) & (px < W) & (py >= 0) & (py < H)
a = np.zeros((H, W), np.uint8); a[py[ok], px[ok]] = 1
ys_, xs_ = np.nonzero(a)
x0, x1, y0, y1 = xs_.min(), xs_.max(), ys_.min(), ys_.max()
fw, fh = int(x1 - x0 + 1), int(y1 - y0 + 1)
bm = a[y0:y1 + 1, x0:x1 + 1].reshape(-1)
bm = np.concatenate([bm, np.zeros((-len(bm)) % 8, np.uint8)]).reshape(-1, 8)
by = (bm * (1 << np.arange(8))).sum(1).astype(int)       # bit k of byte = pixel 8*byte+k

def arr(name, vals, per=24):
    s = "static const uint8_t %s[%d] = {\n" % (name, len(vals))
    for i in range(0, len(vals), per): s += "  " + ",".join("0x%02X" % b for b in vals[i:i + per]) + ",\n"
    return s + "};\n"

print("// Generated by tools/make_demo_data.py, do not edit.")
print("#define HIL_GW %d\n#define HIL_GH %d\n#define HIL_CELL %d" % (GW, GH, CELL))
print("// per cell (row-major): bits 0..3 = the curve leaves the cell to the right, down, left, up; bits 4..6 = section 0..5")
print(arr("hil_tab", tab))
print("#define FERN_X0 %d\n#define FERN_Y0 %d\n#define FERN_W %d\n#define FERN_H %d" % (x0, y0, fw, fh))
print("// 1 bit per pixel, row-major, bit k of byte i = pixel 8*i+k, 1 = black")
print(arr("fern_bm", by))
